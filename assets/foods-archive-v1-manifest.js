/**
 * Returns a picker function that hands out FOODS entries in a shuffled
 * "bag" - every item appears once before any repeat, then the bag reshuffles
 * for the next cycle. Call this once per consumer (raccoon, coin, rolling
 * strip) so each keeps its own independent sequence rather than sharing one
 * global cursor - otherwise using the coin while the raccoon is also
 * cycling would visibly skip entries out from under it.
 */
export function createFoodPicker() {
  let bag = [];
  return function pick() {
    if (bag.length === 0) {
      bag = [...FOODS];
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    return bag.pop();
  };
}
